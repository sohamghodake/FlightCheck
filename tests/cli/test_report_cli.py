"""`flightcheck report REPORT.json` (plan §23.2, §27 Phase 9; ADR-032)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import httpx2
import pytest
from typer.testing import CliRunner

from flightcheck import orchestrator
from flightcheck.cli.app import app
from flightcheck.mock.server import MockServer
from flightcheck.reporting.json_report import REPORT_FILENAME
from flightcheck.runtime import harness

REPO_ROOT = Path(__file__).resolve().parents[2]
APP = REPO_ROOT / "tests" / "fixtures" / "apps" / "bc_bad_tool_pairing"
runner = CliRunner()


@pytest.fixture(autouse=True)
def nothing_runs_or_sends(monkeypatch: pytest.MonkeyPatch) -> None:
    """`report` needs no key, no network and no execution: all of them fail loudly."""

    def boom(*_a: Any, **_k: Any) -> Any:
        raise AssertionError("report must not run, start or send anything")

    monkeypatch.setattr(MockServer, "start", boom)
    monkeypatch.setattr(harness.subprocess, "Popen", boom)
    monkeypatch.setattr(orchestrator, "run_app", boom)
    monkeypatch.setattr(httpx2.Client, "send", boom)


@pytest.fixture
def scan_report(tmp_path: Path) -> Path:
    out = tmp_path / "out"
    result = runner.invoke(app, ["scan", str(APP), "--output", str(out), "--format", "json"])
    assert result.exit_code == 1, result.output
    return out / REPORT_FILENAME


def _report(*args: str) -> Any:
    return runner.invoke(app, ["report", *args, "--no-color"], env={"COLUMNS": "120"})


def test_html_to_output_file(scan_report: Path, tmp_path: Path) -> None:
    """§27 Phase 9 item 14."""
    target = tmp_path / "html" / "r.html"
    result = _report(str(scan_report), "--format", "html", "--output", str(target))
    assert result.exit_code == 0, result.output
    assert result.stdout.strip() == f"HTML report written: {target}"
    html = target.read_text(encoding="utf-8")
    assert html.startswith("<!doctype html>") and "FC-GEN-007" in html
    for section in ("summary", "findings", "scenarios", "ai", "limitations"):
        assert f'<section id="{section}"' in html


def test_default_is_html_next_to_the_report(scan_report: Path) -> None:
    before = scan_report.read_bytes()
    result = _report(str(scan_report))
    assert result.exit_code == 0, result.output
    expected = scan_report.with_name("flightcheck-report.html")
    assert expected.is_file()
    assert result.stdout.strip() == f"HTML report written: {expected}"
    assert scan_report.read_bytes() == before


def test_never_overwrites_the_input(scan_report: Path) -> None:
    before = scan_report.read_bytes()
    result = _report(str(scan_report), "--output", str(scan_report))
    assert result.exit_code == 2
    assert "would overwrite the input report" in result.stderr
    assert scan_report.read_bytes() == before


def test_input_named_html_is_not_overwritten_by_default(scan_report: Path) -> None:
    odd = scan_report.with_name("report.html")
    odd.write_bytes(scan_report.read_bytes())
    result = _report(str(odd))
    assert result.exit_code == 2 and "would overwrite the input report" in result.stderr


def test_output_directory_exits_2(scan_report: Path, tmp_path: Path) -> None:
    result = _report(str(scan_report), "--output", str(tmp_path))
    assert result.exit_code == 2 and "is a directory" in result.stderr


def test_terminal_format_reuses_the_scan_renderer(scan_report: Path) -> None:
    result = _report(str(scan_report), "--format", "terminal")
    assert result.exit_code == 0, result.output
    out = result.stdout
    assert "FlightCheck 0.1.0 · scan · bc_bad_tool_pairing" in out
    assert "FC-GEN-007" in out and f"report: {scan_report}" in out
    assert "Exit " not in out  # report never gates
    assert not list(scan_report.parent.glob("*.html"))


def test_terminal_format_shows_ai_suggestions_of_an_explained_report(scan_report: Path) -> None:
    explained = scan_report.with_name("flightcheck-report.explained.json")
    result = runner.invoke(
        app, ["explain", str(scan_report), "--llm", "fake", "--format", "json", "--repo", str(APP)]
    )
    assert result.exit_code == 0, result.output
    result = _report(str(explained), "--format", "terminal")
    assert result.exit_code == 0, result.output
    assert "FlightCheck 0.1.0 · scan" in result.stdout
    assert "fake LLM, offline; not generated by BharatCode" in result.stdout
    html = _report(str(explained))
    assert html.exit_code == 0, html.output
    text = explained.with_suffix(".html").read_text(encoding="utf-8")
    assert "AI suggestion — not verified, review before applying" in text


def test_terminal_with_output_is_a_usage_error(scan_report: Path, tmp_path: Path) -> None:
    result = _report(str(scan_report), "--format", "terminal", "--output", str(tmp_path / "x"))
    assert result.exit_code == 2 and "--output applies to --format html only" in result.stderr


def test_markdown_is_p1_and_exits_2(scan_report: Path) -> None:
    result = _report(str(scan_report), "--format", "markdown")
    assert result.exit_code == 2
    assert "Markdown output is P1 and not implemented yet." in result.stderr
    assert not list(scan_report.parent.glob("*.html"))
    assert not list(scan_report.parent.glob("*.md"))


def test_unreadable_garbage_and_missing_reports_exit_2(tmp_path: Path) -> None:
    garbage = tmp_path / "garbage.json"
    garbage.write_text("not json", encoding="utf-8")
    not_report = tmp_path / "other.json"
    not_report.write_text('{"hello": 1}', encoding="utf-8")
    invalid = tmp_path / "invalid.json"
    invalid.write_text('{"metadata": {"schema_version": "1.0"}}', encoding="utf-8")
    for path in (garbage, not_report, invalid, tmp_path / "missing.json"):
        result = _report(str(path))
        assert result.exit_code == 2, (path, result.output)
        assert "Error:" in result.stderr
    assert not list(tmp_path.glob("*.html"))


def test_newer_schema_major_exits_2(scan_report: Path) -> None:
    data = json.loads(scan_report.read_text(encoding="utf-8"))
    data["metadata"]["schema_version"] = "2.0"
    newer = scan_report.with_name("newer.json")
    newer.write_text(json.dumps(data), encoding="utf-8")
    result = _report(str(newer))
    assert result.exit_code == 2
    assert "Unsupported report schema version '2.0'" in result.stderr


def test_help_lists_report_as_available() -> None:
    result = runner.invoke(app, ["--help"])
    available = result.output.split("Coming in later phases")[0]
    assert "report REPORT.json" in available
    assert "ci PATH" in result.output.split("Coming in later phases")[1]
