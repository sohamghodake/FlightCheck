"""Deterministic offline backend for ``--llm fake`` (plan §19.2).

Builds schema-valid explanations from the request's own input (rule metadata only), so tests
and demos without a key exercise the same parsing and validation path as BharatCode. Every
text starts with :data:`FAKE_PREFIX`; nothing here is generated by a model.
"""

from __future__ import annotations

import json
from typing import Any

from flightcheck.diagnostics.schema import AIExplanation, AIExplanationBatch
from flightcheck.providers.base import ResponsesRequest

FAKE_PREFIX = "[FAKE LLM — not generated by BharatCode]"
FAKE_MODEL = "fake-llm"

__all__ = ["FAKE_MODEL", "FAKE_PREFIX", "FakeLLM"]


def _text(body: str, limit: int) -> str:
    text = f"{FAKE_PREFIX} {body}".strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


class FakeLLM:
    """``respond(request) -> str``: a JSON :class:`AIExplanationBatch` for every group."""

    model = FAKE_MODEL

    def respond(self, request: ResponsesRequest) -> str:
        document: dict[str, Any] = json.loads(str(request.input))
        explanations = [self._explain(group) for group in document.get("groups", [])]
        return AIExplanationBatch(explanations=explanations).model_dump_json()

    @staticmethod
    def _explain(group: dict[str, Any]) -> AIExplanation:
        rule_id = str(group.get("rule_id", ""))
        title = str(group.get("title", rule_id))
        remediation = str(group.get("remediation") or "No deterministic remediation is known.")
        instances = group.get("instances", [])
        ids = [str(item.get("finding_id")) for item in instances if item.get("finding_id")]
        where = ", ".join(
            f"{item['path']}:{item.get('line', 0)}" for item in instances if item.get("path")
        )
        return AIExplanation(
            rule_id=rule_id,
            finding_ids=ids,
            summary=_text(f"{rule_id} ({title}): {len(ids)} instance(s) selected.", 600),
            root_cause=_text(
                f"FlightCheck reported '{title}'"
                + (f" at {where}" if where else "")
                + ". This placeholder restates the rule metadata; it adds no analysis.",
                1200,
            ),
            impact=_text(f"Severity '{group.get('severity', 'unknown')}' per the rule.", 800),
            fix_steps=[_text(remediation, 600)],
            patch=None,
            caveats=[_text("Offline fake backend: run --llm bharatcode for a real one.", 300)],
            model_stated_confidence="low",
        )
